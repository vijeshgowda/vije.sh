/**
 * Generates src/features/overview/timezone-countries.ts (IANA time zone -> ISO country). Two
 * sources, both keyed by country so a zone is never credited to the wrong one:
 *   - zone.tab from the public-domain tz database: current IANA names (Asia/Kolkata).
 *   - ICU/CLDR via Intl.Locale#getTimeZones(): the older IDs ICU-based browsers still report
 *     (Asia/Calcutta, Pacific/Truk, America/Coral_Harbour).
 * tzdata links are not followed: many now point at a same-rules zone in another country.
 *   npx tsx scripts/timezone-countries.ts [/usr/share/zoneinfo]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2] ?? "/usr/share/zoneinfo";
const out = "src/features/overview/timezone-countries.ts";
const tab = (f: string) =>
  readFileSync(join(dir, f), "utf8")
    .split("\n")
    .filter((l) => l && !l.startsWith("#"))
    .map((l) => l.split("\t"));

const zones = new Map<string, Set<string>>();
const add = (cc: string, zone: string) => zones.set(cc, (zones.get(cc) ?? new Set()).add(zone));

for (const [cc, , zone] of tab("zone.tab")) if (cc && zone) add(cc, zone);
for (const [cc] of tab("iso3166.tab")) {
  if (!cc) continue;
  const icu = (new Intl.Locale(`und-${cc}`) as Intl.Locale & { getTimeZones?(): string[] })
    .getTimeZones?.()
    ?.filter((z) => z.includes("/") && !z.startsWith("Etc/"));
  icu?.forEach((z) => add(cc, z));
}

const owner = new Map<string, string>();
for (const [cc, set] of zones)
  for (const z of set) {
    const prev = owner.get(z);
    if (prev && prev !== cc) throw new Error(`${z} is in both ${prev} and ${cc}`);
    owner.set(z, cc);
  }

const version = readFileSync(join(dir, "tzdata.zi"), "utf8")
  .split("\n")[0]
  ?.replace(/^# version /, "");
const rows = [...zones]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([cc, set]) => `  ${cc}: "${[...set].sort().join(" ")}",`);

writeFileSync(
  out,
  `// Generated by scripts/timezone-countries.ts from tzdata ${version} and ICU ${process.versions.icu}.\n` +
    `// Do not edit by hand.\n` +
    `/** ISO 3166 country code -> space-separated IANA time zones in that country. */\n` +
    `export const ZONES_BY_COUNTRY: Readonly<Record<string, string>> = {\n${rows.join("\n")}\n};\n`,
);
console.log(`timezone-countries: ${owner.size} zones in ${zones.size} countries -> ${out}`);
