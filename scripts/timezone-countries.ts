/**
 * Generates src/features/overview/timezone-countries.ts (IANA time zone -> ISO country) from the
 * public-domain tz database. Canonical zones come from zone.tab; legacy aliases that browsers still
 * report (Asia/Calcutta, US/Eastern) come from the links in tzdata.zi. Zones without a country
 * (UTC, Etc/*) and abbreviation zones (EST, CET, EST5EDT) are left out on purpose.
 *   npx tsx scripts/timezone-countries.ts [/usr/share/zoneinfo]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2] ?? "/usr/share/zoneinfo";
const out = "src/features/overview/timezone-countries.ts";
const read = (f: string) => readFileSync(join(dir, f), "utf8").split("\n");

const country = new Map<string, string>();
for (const line of read("zone.tab")) {
  if (!line || line.startsWith("#")) continue;
  const [cc, , zone] = line.split("\t");
  if (cc && zone) country.set(zone, cc);
}
const zi = read("tzdata.zi");
const version = zi[0]?.replace(/^# version /, "") ?? "unknown";
for (const line of zi) {
  const [kind, target, alias] = line.split(" ");
  if (kind !== "L" || !target || !alias || country.has(alias)) continue;
  if (/^(?:[A-Z]ST|[CEMW]ET|[A-Z]ST\d[A-Z]DT)$/.test(alias)) continue;
  const cc = country.get(target);
  if (cc) country.set(alias, cc);
}

const byCountry = new Map<string, string[]>();
for (const [zone, cc] of country) byCountry.set(cc, [...(byCountry.get(cc) ?? []), zone]);
const rows = [...byCountry]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([cc, zones]) => `  ${cc}: "${zones.sort().join(" ")}",`);

writeFileSync(
  out,
  `// Generated by scripts/timezone-countries.ts from tzdata ${version}. Do not edit by hand.\n` +
    `/** ISO 3166 country code -> space-separated IANA time zones in that country. */\n` +
    `export const ZONES_BY_COUNTRY: Readonly<Record<string, string>> = {\n${rows.join("\n")}\n};\n`,
);
console.log(`timezone-countries: ${country.size} zones in ${byCountry.size} countries -> ${out}`);
