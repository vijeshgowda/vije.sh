import fs from "node:fs";
import path from "node:path";

/**
 * Notes (app.posts) and git posts (content/blog/<slug>/) share the /blog/<slug> URL space
 * (application.md 9.4). Server Actions can't read content/blog at runtime (it's only traced into
 * the /blog routes), so scripts/copy-blog-assets.ts writes the git slugs to git-slugs.json, which
 * is bundled like any other import. The file is committed so typecheck and tests never depend on
 * a prior build; a unit test fails when it's out of date. No "server-only": the script runs this
 * outside Next.js.
 */

export const GIT_SLUGS_FILE = path.join(
  process.cwd(),
  "src",
  "features",
  "blog",
  "notes",
  "git-slugs.json",
);

export interface GitSlugManifest {
  $comment: string;
  slugs: string[];
}

const COMMENT =
  "Generated by scripts/copy-blog-assets.ts (npm run blog:assets) from content/blog. Do not edit.";

/** Every post folder under content/blog, sorted. Drafts and unlisted posts count too. */
export function readGitSlugs(contentDir: string): string[] {
  if (!fs.existsSync(contentDir)) return [];
  return fs
    .readdirSync(contentDir, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();
}

export function manifestText(slugs: string[]): string {
  const manifest: GitSlugManifest = { $comment: COMMENT, slugs };
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

/** Rewrites the manifest when the git slugs changed. Returns true when it wrote the file. */
export function writeGitSlugManifest(contentDir: string, file = GIT_SLUGS_FILE): boolean {
  const text = manifestText(readGitSlugs(contentDir));
  if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === text) return false;
  fs.writeFileSync(file, text);
  return true;
}
